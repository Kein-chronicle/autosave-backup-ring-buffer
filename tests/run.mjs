import test from 'node:test';
import assert from 'node:assert/strict';
import {planBackup} from '../scripts/backup.mjs';
test('default plan writes to a fresh key and drops older snapshots only afterwards',()=>{
 const original=[{key:'backup-0',savedAt:1},{key:'backup-1',savedAt:2},{key:'backup-2',savedAt:3}];
 assert.equal(planBackup([],2,1).key,'backup-0');
 const p=planBackup(original,2,4);
 assert.equal(p.key,'backup-3');                                   // never one of the existing keys
 assert.deepEqual(p.dropped,['backup-1','backup-0']);             // to delete after the new snapshot is durable
 assert.deepEqual(p.entries.map(x=>x.savedAt),[4,3]);assert.equal(original.length,3);
 const one=planBackup([{key:'backup-0',savedAt:1}],1,2);          // keep=1: the old snapshot survives until the new one is stored
 assert.equal(one.key,'backup-1');assert.deepEqual(one.dropped,['backup-0']);
});
test('inPlace reuses the oldest slot (fixed slot count, NOT crash-safe)',()=>{
 const original=[{key:'backup-0',savedAt:1},{key:'backup-1',savedAt:2},{key:'backup-2',savedAt:3}];
 const p=planBackup(original,2,4,{inPlace:true});assert.equal(p.key,'backup-1');assert.deepEqual(p.dropped,['backup-0']);
 assert.equal(planBackup([{key:'backup-0',savedAt:1}],1,2,{inPlace:true}).key,'backup-0');   // overwrites the only snapshot: documented hazard
});
test('a key generated by the planner never collides with an existing one',()=>{
 let idx=[];for(let t=1;t<=20;t++){const p=planBackup(idx,3,t);assert.ok(!idx.some(e=>e.key===p.key));idx=p.entries;assert.ok(idx.length<=3);}
});
test('invalid indexes and backward clocks do not delete history',()=>{
 assert.throws(()=>planBackup([{key:'a',savedAt:10}],2,9));
 assert.throws(()=>planBackup([{key:'a',savedAt:1},{key:'a',savedAt:2}],2,3));
 for(const n of [0,1.5,Infinity])assert.throws(()=>planBackup([],n,1));
});
